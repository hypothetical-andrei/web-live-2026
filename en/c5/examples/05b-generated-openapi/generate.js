// Generate export artifacts from the assembled OpenAPI document. The tiny client template
// supports this one JSON POST, not arbitrary OpenAPI.
import { mkdir, writeFile } from "node:fs/promises";
import { buildOpenApi } from "./openapi.js";

const description = buildOpenApi();
const output = new URL("./generated/", import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(
  new URL("openapi.json", output),
  JSON.stringify(description, null, 2) + "\n",
);

const [path, methods] = Object.entries(description.paths)[0];
const [method, operation] = Object.entries(methods)[0];
if (method !== "post" || !/^[A-Za-z_$][\w$]*$/.test(operation.operationId)) {
  throw new Error("This teaching generator supports one named JSON POST operation.");
}
const client = `// Generated by npm run generate. Edit schemas/operation metadata instead.
export async function ${operation.operationId}(body, baseUrl = "") {
  const response = await fetch(baseUrl + ${JSON.stringify(path)}, {
    method: ${JSON.stringify(method.toUpperCase())},
    headers: { "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify(body),
  });
  const result = await response.json();
  if (!response.ok) {
    throw Object.assign(new Error(result.error.code), { status: response.status });
  }
  return result;
}
`;
await writeFile(new URL("client.js", output), client);

await writeFile(
  new URL("index.html", output),
  `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Generated API interface</title>
    <link rel="stylesheet" href="/docs/assets/swagger-ui.css" />
  </head>
  <body>
    <h1>Generated API interface</h1>
    <p><a href="/openapi.json">OpenAPI specification</a> · <a href="/client.js">Generated JavaScript client</a></p>
    <div id="swagger-ui"></div>
    <script src="/docs/assets/swagger-ui-bundle.js"></script>
    <script>
      window.ui = SwaggerUIBundle({
        url: "/openapi.json",
        dom_id: "#swagger-ui",
        validatorUrl: null,
      });
    </script>
  </body>
</html>
`,
);
console.log("Generated OpenAPI, client.js and Swagger UI page.");
